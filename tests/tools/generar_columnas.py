#!/usr/bin/env python3
"""
Genera tests/DKbase.Tests/TestInfra/ColumnasConocidas.g.cs a partir del código de producción.
Busca cada acceso a columna por nombre (fila["columna"]) e infiere el tipo por la conversión que lo rodea.
Se usa para armar la "base universal" del golden master: una tabla que tiene todas las columnas que el código lee.
Uso: python3 tests/tools/generar_columnas.py   (desde la raíz del repo)
"""
import os, re, collections

RAIZ = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
acceso = re.compile(r'(Convert\.To(\w+)\s*\(\s*)?(?:\(\s*(int|bool|decimal|double|DateTime|string|long)\??\s*\)\s*)?[\w\.\[\]\(\)]*\[\s*"([A-Za-z_][\w]*)"\s*\](\.ToString\(\))?')
tipos = collections.defaultdict(collections.Counter)
for dirpath, dirs, files in os.walk(RAIZ):
    if "/tests" in dirpath or "/.git" in dirpath or "/obj" in dirpath or "/bin" in dirpath:
        continue
    for f in files:
        if not f.endswith(".cs"):
            continue
        txt = open(os.path.join(dirpath, f), encoding="utf-8-sig").read()
        for m in acceso.finditer(txt):
            conv, cast, col = m.group(2), m.group(3), m.group(4)
            t = None
            if conv:
                t = {"Int32": "int", "Int16": "int", "Int64": "int", "Boolean": "bool", "Decimal": "decimal", "Double": "decimal",
                     "DateTime": "DateTime", "String": "string"}.get(conv)
            elif cast:
                t = {"int": "int", "long": "int", "bool": "bool", "decimal": "decimal", "double": "decimal", "DateTime": "DateTime", "string": "string"}[cast]
            tipos[col][t or "?"] += 1

def elegir(c):
    # precedencia: DateTime y bool necesitan su tipo; int sirve también para ToString y ToDecimal
    for t in ("DateTime", "bool", "decimal", "int"):
        if c[t]:
            return t
    return "string"

lineas = ["// <auto-generated> por tests/tools/generar_columnas.py. No editar a mano. </auto-generated>",
          "using System;", "using System.Collections.Generic;", "", "namespace DKbase.Tests.TestInfra", "{",
          "    public static class ColumnasConocidas", "    {",
          "        public static readonly IReadOnlyDictionary<string, Type> Todas = new Dictionary<string, Type>(StringComparer.OrdinalIgnoreCase)", "        {"]
mapa = {"int": "typeof(int)", "bool": "typeof(bool)", "decimal": "typeof(decimal)", "DateTime": "typeof(DateTime)", "string": "typeof(string)"}
vistos = set()
for col in sorted(tipos, key=str.lower):
    if col.lower() in vistos:
        continue
    vistos.add(col.lower())
    lineas.append(f'            ["{col}"] = {mapa[elegir(tipos[col])]},')
lineas += ["        };", "    }", "}", ""]
destino = os.path.join(RAIZ, "tests", "DKbase.Tests", "TestInfra", "ColumnasConocidas.g.cs")
open(destino, "w", encoding="utf-8").write("\n".join(lineas))
print(f"{len(vistos)} columnas -> {destino}")
